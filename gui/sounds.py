"""
Designed earcons for VYUK — earcon set v3 (v5.51 polish pack).

A coherent, soft synthesized family (see gen_earcons.py at the Code Lab
root — the WAVs in gui/assets are generated by it, never sampled):
  wake        E5 -> A5 two-note rise        — wake word heard
  ack         E5 single soft blip           — instant acknowledgement
  sent        C#5 single blip               — message sent
  done        F#5 -> B5 two-note rise       — task finished
  error       low A thud                    — something failed
  connect     A4 -> E5 rising bloom         — session connected
  disconnect  E5 -> A4 falling resolve      — session closed
  ready       A-major arpeggio              — offline pack finished
  capture     short high tick               — screenshot / screen share
  alert       soft double-pulse             — watcher notice (never alarming)

Tiny synthesized WAVs in gui/assets, played through QSoundEffect.
Everything is guarded: if QtMultimedia is unavailable or the platform
has no audio, the app silently runs without sounds. Sounds must never
break the assistant.
"""

from pathlib import Path

try:
    from PySide6.QtCore import QUrl
    from PySide6.QtMultimedia import QSoundEffect

    _AVAILABLE = True
except Exception:  # noqa: BLE001
    _AVAILABLE = False

_ASSETS = Path(__file__).resolve().parent / "assets"

#: Every cue in the v3 family, in design order (v3 adds "ack", the
#: instant-acknowledgement receipt blip, right after "wake").
#: Phase F (guide S14 sound identity) adds the overlay cues:
#: "lock" (target-lock tick), "start" (low pulse when execution
#: starts), "step" (soft tick per completed step), "handback"
#: (falling sweep when control returns), "toast" (toast cue).
#: The WAVs for the five new cues are generated by the same
#: recipe as the v3 set (48 kHz mono 16-bit, RMS -20 dBFS, soft
#: raised-cosine attacks) — see the Phase F record.
CUE_NAMES = (
    "wake", "ack", "sent", "done", "error",
    "connect", "disconnect", "ready", "capture", "alert",
    "lock", "start", "step", "handback", "toast",
)


#: Earcon families (v5.17): "classic" is the set in gui/assets;
#: "soft" is the gentler family in gui/assets/earcons_soft — same
#: ten cue filenames and the same melodic identity, softer timbre.
FAMILIES = ("classic", "soft")


class Earcons:
    def __init__(self, parent=None, volume: float = 0.5, enabled: bool = True,
                 family: str = "classic"):
        self.enabled = enabled
        self.volume = volume
        self._parent = parent
        self.family = family if family in FAMILIES else "classic"
        self._cue_enabled = {name: True for name in CUE_NAMES}
        self._effects = {}
        self._load_effects()

    def _family_dir(self) -> Path:
        return _ASSETS if self.family == "classic" else _ASSETS / "earcons_soft"

    def _load_effects(self):
        for effect in self._effects.values():
            try:
                effect.deleteLater()
            except Exception:  # noqa: BLE001
                pass
        self._effects = {}
        if not _AVAILABLE:
            return
        base = self._family_dir()
        for name in CUE_NAMES:
            path = base / f"{name}.wav"
            if not path.exists():
                continue
            try:
                effect = QSoundEffect(self._parent)
                effect.setSource(QUrl.fromLocalFile(str(path)))
                effect.setVolume(self.volume)
                self._effects[name] = effect
            except Exception:  # noqa: BLE001
                continue

    def set_family(self, family: str):
        """Switches the cue family live (v5.17); unknown names and
        re-selecting the current family are no-ops."""
        if family not in FAMILIES or family == self.family:
            return
        self.family = family
        self._load_effects()

    def set_cue_enabled(self, name: str, enabled: bool):
        """Per-cue mute (v5.17): a disabled cue never plays, even
        with interface sounds on."""
        if name in self._cue_enabled:
            self._cue_enabled[name] = bool(enabled)

    def cue_enabled(self, name: str) -> bool:
        return self._cue_enabled.get(name, True)

    def set_volume(self, volume: float):
        self.volume = volume
        for effect in self._effects.values():
            effect.setVolume(volume)

    def set_enabled(self, enabled: bool):
        self.enabled = enabled

    def _play(self, name: str):
        if not self.enabled or not self._cue_enabled.get(name, True):
            return
        # Conversion Wave 9: the sonic canon gates every emission.
        # Denied (unknown cue, hero misuse, frequency cap) means
        # silence, never a substitute sound. No earcon asset is
        # added or layered by this gate — the veto stands.
        try:
            from voice_assistant.core.gui_facade import w9_wiring as _w9
            if not _w9.gate_sound_emission(name, self.family):
                return
        except Exception:  # noqa: BLE001 — a gate fault never breaks audio
            pass
        effect = self._effects.get(name)
        if effect is not None:
            try:
                effect.play()
            except Exception:  # noqa: BLE001
                pass

    def wake(self):
        self._play("wake")

    def ack(self):
        self._play("ack")

    def sent(self):
        self._play("sent")

    def done(self):
        self._play("done")

    def error(self):
        self._play("error")

    def connect(self):
        self._play("connect")

    def disconnect(self):
        self._play("disconnect")

    def ready(self):
        self._play("ready")

    def capture(self):
        self._play("capture")

    def alert(self):
        self._play("alert")

    def lock(self):
        self._play("lock")

    def start(self):
        self._play("start")

    def step(self):
        self._play("step")

    def handback(self):
        self._play("handback")

    def toast(self):
        self._play("toast")
