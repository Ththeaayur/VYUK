"""
Creative skills pack II for VYUK (v5.14) — creativity, deepened:
escape-time fractals, a three-layer song composer, a synthesised
drum machine, a name generator, three-act story outlines and
guaranteed-form haiku.

LICENCE: everything these tools produce is generated by code in
this module at call time — fractals are arithmetic, songs and
beats are synthesised sine/noise with the stdlib only, names,
outlines and haiku are combinations of the banks below. No
external assets, no samples, no copied banks, nothing made "in
the style of" anyone. (The drum synthesis is deliberately
primitive — sine-drop kicks and differenced-noise hats; the
descriptions say so rather than dressing it up.)

Same rules as the other packs: plain functions returning
human-readable strings; handlers never raise and never fake a
result — a refusal or an error line says exactly why. Caps are
enforced in the open and disclosed in the result. Generative
outputs are seeded and deterministic (seed 0 picks one and
reports it, so the user can iterate); the beat machine is the one
exception — it has no seed because a drum loop's identity is its
style + tempo, and it says so.

Read/write split: name_generator, story_outline and haiku only
compute text (READ-ONLY); fractal_art, compose_song and
generate_beat each write one media file, never overwriting — a
taken name gets a " (2)"-style suffix and the result says so.
Pictures go to ~/Pictures/Nova/, audio to ~/Music/Nova/, the
house media homes. Pure stdlib except fractal_art, which lazily
imports Pillow the way the media packs do. This pack re-implements
the small shared helpers locally — packs never import packs.

Wiring: the parent (core/funnel/tools_registry.py) calls register_all(registry) — this
module never touches the registry singleton itself.
"""

