# Result-card category icons: tool-name fragment -> icons.py icon name.
# Only icons that exist in icons.py are used; anything unmatched gets the
# generic "spark". First match wins, so order goes specific -> broad.
TOOL_ICONS = (
    (("lock",), "check"),
    (("screenshot", "webcam", "ocr", "screen", "display", "network"), "monitor"),
    (("browser", "web_search", "url", "weather", "download"), "search"),
    (("reminder", "schedule", "plan", "routine", "time", "date"), "clock"),
    (("volume", "media"), "volume"),
    (("memory", "remember", "recall", "fact"), "database"),
    (("system", "process", "battery"), "sliders"),
    (("launch", "open_path", "application"), "grid"),
)

def tool_icon_name(tool_name: str) -> str:
    low = (tool_name or "").lower().replace(" ", "_")
    for keys, icon in TOOL_ICONS:
        if any(k in low for k in keys):
            return icon
    return "spark"



