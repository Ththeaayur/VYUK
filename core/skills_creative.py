# ---------------------------------------------------------------------------


def register_all(registry) -> None:
    """Register every Creative pack tool on a ToolRegistry-like object."""
    registry.register(
        name="ascii_art",
        description="Render text in a chunky 5-row block-letter font drawn into VYUK itself (no external fonts). Supports letters A-Z (lowercase is folded up), digits 0-9, spaces and the punctuation . , ! ? ' - : — anything else gets an honest refusal naming what can't be drawn. Input is capped at 24 characters because block letters get wide fast. Returns the art as text, ideal for banners, logos-as-text and a bit of flair in chat.",
        parameters={
            "type": "object",
            "properties": {
                "text": {"type": "string", "description": "The word or short phrase to render (up to 24 characters)"},
            },
            "required": ["text"],
        },
        handler=ascii_art,
    )
    registry.register(
        name="generate_palette",
        description="Build a five-colour palette from colour-harmony maths (HSV): complementary, analogous, triadic or monochrome — or 'random' to let VYUK pick the harmony. Give a base colour as #RRGGBB (e.g. #3B82F6) or leave it empty for a random hue. Returns five hex colours with role labels (base, complement, deep shade...) as text — handy for design, slides, rooms and outfits. Nothing is written to disk.",
        parameters={
            "type": "object",
            "properties": {
                "style": {"type": "string", "enum": ["complementary", "analogous", "triadic", "monochrome", "random"], "description": "The harmony to build (default random)"},
                "base": {"type": "string", "description": "Base colour as #RRGGBB (optional; a random hue is used when empty)"},
            },
            "required": [],
        },
        handler=generate_palette,
    )
    registry.register(
        name="create_art",
        description="Draw an original generative picture with code and save it as a PNG: 'circles' (overlapping translucent circles), 'lines' (flowing ribbons), 'mosaic' (a grid of harmony-coloured tiles), 'gradient' (a smooth multi-stop diagonal blend), 'phyllotaxis' (a golden-angle sunflower spiral) or 'starfield' (a night sky with a glow cluster). The seed fixes both the picture and its colour palette, so the same seed always recreates the same image — seed 0 picks one and reports it, so the user can iterate ('same seed, another style'). Size is 256–2048 pixels square. Default save is ~/Pictures/Nova/nova_art_<style>_<seed>.png; an existing file is never overwritten (a ' (2)' suffix is added and reported).",
        parameters={
            "type": "object",
            "properties": {
                "style": {"type": "string", "enum": ["circles", "lines", "mosaic", "gradient", "phyllotaxis", "starfield"], "description": "Picture style (default circles)"},
                "seed": {"type": "integer", "description": "Seed for the picture + palette (0 = pick one and report it)"},
                "size": {"type": "integer", "description": "Square size in pixels, 256–2048 (default 512)"},
                "output": {"type": "string", "description": "Optional output path (default ~/Pictures/Nova/)"},
            },
            "required": [],
        },
        handler=create_art,
    )
    registry.register(
        name="generate_melody",
        description="Compose a short ORIGINAL melody and save it as a WAV file — synthesised note by note with code (sine + octave harmonic, decaying envelope), never sampled or copied. Moods set the scale and tempo: 'calm' (C major pentatonic, slow), 'bright' (C major, quicker), 'melancholy' (A natural minor, slow), 'playful' (C major with leaps). The seed fixes the tune, so the same seed + mood always recreates the same melody; seed 0 picks one and reports it. Length is 4–30 seconds. Default save is ~/Music/Nova/nova_melody_<mood>_<seed>.wav; an existing file is never overwritten (a ' (2)' suffix is added and reported).",
        parameters={
            "type": "object",
            "properties": {
                "mood": {"type": "string", "enum": ["calm", "bright", "melancholy", "playful"], "description": "Mood = scale + tempo (default calm)"},
                "seed": {"type": "integer", "description": "Seed for the tune (0 = pick one and report it)"},
                "seconds": {"type": "number", "description": "Length in seconds, 4–30 (default 12)"},
                "output": {"type": "string", "description": "Optional output path (default ~/Music/Nova/)"},
            },
            "required": [],
        },
        handler=generate_melody,
    )
    registry.register(
        name="writing_prompt",
        description="Deal a fresh writing prompt by combining a protagonist, a situation, a twist and a setting from VYUK's own fragment banks. Genres: fantasy, sci_fi, mystery, romance, horror — or 'any' for a surprise genre (the result names the genre it picked). Pure text, nothing written to disk; ask again for a different combination.",
        parameters={
            "type": "object",
            "properties": {
                "genre": {"type": "string", "enum": ["any", "fantasy", "sci_fi", "mystery", "romance", "horror"], "description": "Genre bank to draw from (default any)"},
            },
            "required": [],
        },
        handler=writing_prompt,
    )
