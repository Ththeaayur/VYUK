"""
Creative skills pack for VYUK (v5.13) — five make-something tools:
block-letter ASCII art, colour-palette harmonies, seeded generative
pictures, a synthesised original melody, and writing prompts.

LICENCE: everything these tools produce is generated by code in
this module at call time — the block font is drawn by hand as data
below, palettes are HSV arithmetic, pictures are PIL primitives,
melodies are synthesised sine waves, prompts are combinations of
the fragment banks below. No external assets, no bundled fonts,
samples or images, and nothing made "in the style of" anyone.

Same rules as the other packs: plain functions returning
human-readable strings; handlers never raise and never fake a
result — a refusal or an error line says exactly why. Caps (ASCII
input length, art size, melody length, output truncation) are
enforced in the open and disclosed in the result.

Read/write split: ascii_art, generate_palette and writing_prompt
only compute text (READ-ONLY); create_art and generate_melody write
one media file each, never overwriting — a taken name gets a
" (2)"-style suffix and the result says so. Stdlib-only except
create_art, which lazily imports Pillow the way the media packs do.

Wiring: the parent (core/funnel/tools_registry.py) calls register_all(registry) — this
module never touches the registry singleton itself.
"""

