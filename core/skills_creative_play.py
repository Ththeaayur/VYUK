def _load_corpus() -> tuple[list, str]:
    """(words, source_description) for anagram hunting.

    Order: the word lists the games pack already ships (hangman +
    word-game banks, imported lazily); else /usr/share/dict/words;
    else this module's built-in fallback bank. The description is
    reported in the result so the corpus size is never a mystery.
    """
    try:
        from . import skills_games

        words = set()
        for bank in (skills_games._HANGMAN_WORDS,
                     skills_games._WORDLE_WORDS):
            for word in bank:
                cleaned = word.strip().lower()
                if cleaned.isalpha():
                    words.add(cleaned)
        if words:
            return (sorted(words),
                    f"VYUK's built-in game word lists "
                    f"({len(words)} words)")
    except Exception:  # noqa: BLE001 — fall through to the dictionary
        pass
    dict_path = Path("/usr/share/dict/words")
    try:
        if dict_path.is_file():
            words = set()
            for line in dict_path.read_text(
                    encoding="utf-8", errors="replace").splitlines():
                cleaned = line.strip().lower()
                if cleaned.isalpha():
                    words.add(cleaned)
            if words:
                return (sorted(words),
                        f"the system dictionary ({len(words)} words)")
    except Exception:  # noqa: BLE001 — fall through to the fallback
        pass
    return (sorted(set(_FALLBACK_WORDS)),
            f"the built-in fallback bank ({len(set(_FALLBACK_WORDS))} "
            "words — no dictionary was found on this system)")


def anagram_finder(letters: str, limit: int = 10) -> str:
    """Exact anagrams and the longest sub-anagrams of a letter set."""
    cleaned = re.sub(r"[^a-z]", "", (letters or "").lower())
    if len(cleaned) < 3:
        return ("Give me at least 3 letters to hunt anagrams in — "
                "e.g. anagram_finder('listen').")
    try:
        cap = int(limit)
    except (TypeError, ValueError):
        return f"'{limit}' isn't a number of results."
    cap = max(1, min(50, cap))
    have = Counter(cleaned)
    words, source = _load_corpus()
    exact, subs = [], []
    for word in words:
        if len(word) < 3 or len(word) > len(cleaned):
            continue
        need = Counter(word)
        if need - have:
            continue
        if len(word) == len(cleaned):
            if word != cleaned:
                exact.append(word)
        elif len(word) >= 4:
            subs.append(word)
    subs.sort(key=lambda w: (-len(w), w))
    exact.sort()
    if not exact and not subs:
        return (f"No anagrams hide in '{cleaned}' — I searched "
                f"{source} and found nothing of 4+ letters (or an "
                "exact shuffle).")
    lines = []
    if exact:
        lines.append(f"Exact anagrams of '{cleaned}': "
                     + ", ".join(exact) + ".")
    if subs:
        shown = subs[:cap]
        lines.append(f"Longest words hiding inside ({len(subs)} "
                     f"found, longest first): "
                     + ", ".join(shown)
                     + ("…" if len(subs) > len(shown) else "") + ".")
    lines.append(f"(Searched {source}.)")
    return "\n".join(lines)


