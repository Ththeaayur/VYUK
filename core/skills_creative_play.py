"""
Creative skills III for VYUK (v5.21, HANDS) — six more
make-something tools: read a picture's dominant colours, build a
CSS gradient (with a picture of it), roll story dice, hunt
anagrams, and synthesise two kinds of sound — a metronome click
track and a binaural tone pair.

LICENCE: everything here is generated by code in this module at
call time — palettes are PIL quantisation over the user's own
image, gradients are interpolation maths, dice faces are the
in-module banks below, anagrams come from word lists already in
the product (or the system's dictionary), and the sounds are
sine waves rendered sample by sample. No external assets.

Same rules as the other packs: plain functions returning
human-readable strings; handlers never raise and never fake a
result — a refusal or an error line says exactly why. Caps are
enforced in the open and disclosed in the result.

Read/write split: story_dice and anagram_finder only compute
text, and color_from_image only reads (READ-ONLY); gradient_css
returns text AND writes one preview PNG, metronome and
binaural_tone each write one WAV. Writers follow the house
conventions: media folders under the home directory (~/Pictures
/Nova, ~/Music/Nova) and a taken name gets a " (2)"-style suffix
that the result discloses — a created file never overwrites.

Wiring: the parent (core/funnel/tools_registry.py) calls register_all(registry) — this
module never touches the registry singleton itself.
"""

import math
import random
import re
import sys
import wave
from array import array
from collections import Counter
from pathlib import Path

_SAMPLE_RATE = 44100  # the audio packs' CD-rate standard for new tools

# ---------------------------------------------------------------------------
# Shared helpers (each pack carries its own copies — the house convention)
# ---------------------------------------------------------------------------


def _non_clobbering(dest: Path) -> Path:
    """Return `dest`, or 'stem (2).suffix', 'stem (3).suffix', … —
    the house rule: a created file never silently overwrites."""
    if not dest.exists():
        return dest
    counter = 2
    while True:
        candidate = dest.with_name(f"{dest.stem} ({counter}){dest.suffix}")
        if not candidate.exists():
            return candidate
        counter += 1


def _suffix_note(dest: Path, final: Path) -> str:
    """The disclosure sentence when a taken name was suffixed."""
    if final == dest:
        return ""
    return (f" '{dest.name}' already existed, so the suffixed name "
            f"'{final.name}' was used instead.")


def _save_wav(final: Path, samples: array, channels: int) -> None:
    """Write 16-bit samples as a WAV at the pack sample rate."""
    if sys.byteorder == "big":
        samples = array("h", samples)
        samples.byteswap()
    with wave.open(str(final), "wb") as wav:
        wav.setnchannels(channels)
        wav.setsampwidth(2)
        wav.setframerate(_SAMPLE_RATE)
        wav.writeframes(samples.tobytes())


