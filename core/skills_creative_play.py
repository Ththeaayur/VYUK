# A small named-colour table (~24 anchors) — nearest wins by
# Euclidean distance in RGB, so a name is an approximation and the
# result always gives the exact hex alongside it.
_NAMED_COLOURS = (
    ("black", (0, 0, 0)), ("white", (255, 255, 255)),
    ("silver", (192, 192, 192)), ("gray", (128, 128, 128)),
    ("maroon", (128, 0, 0)), ("red", (220, 30, 40)),
    ("crimson", (190, 20, 50)), ("coral", (255, 127, 80)),
    ("orange", (255, 140, 0)), ("gold", (230, 190, 40)),
    ("yellow", (245, 230, 60)), ("beige", (232, 218, 190)),
    ("brown", (130, 82, 45)), ("olive", (110, 115, 40)),
    ("lime", (90, 220, 60)), ("green", (30, 150, 70)),
    ("teal", (0, 130, 130)), ("turquoise", (64, 210, 200)),
    ("cyan", (0, 195, 235)), ("sky blue", (120, 185, 235)),
    ("blue", (35, 80, 210)), ("navy", (15, 25, 110)),
    ("indigo", (70, 60, 170)), ("purple", (135, 60, 180)),
    ("lavender", (185, 165, 225)), ("magenta", (215, 40, 180)),
    ("pink", (245, 165, 195)),
)


def _nearest_colour_name(rgb: tuple) -> str:
    best, best_dist = "", None
    for name, anchor in _NAMED_COLOURS:
        dist = sum((c - a) ** 2 for c, a in zip(rgb, anchor))
        if best_dist is None or dist < best_dist:
            best, best_dist = name, dist
    return best


def color_from_image(path: str, count: int = 5) -> str:
    """The dominant colours of a picture, as hex + name + share."""
    try:
        n = int(count)
    except (TypeError, ValueError):
        return f"'{count}' isn't a number of colours."
    n = max(1, min(10, n))
    target = Path(str(path or "")).expanduser()
    if not target.is_file():
        return f"'{path}' isn't a picture file I can open."
    try:
        from PIL import Image
    except ImportError:
        return ("The image part didn't make it into this build of "
                "VYUK, so I can't read pictures.")
    try:
        with Image.open(target) as img:
            rgb = img.convert("RGB")
            rgb.thumbnail((256, 256))
            quantised = rgb.quantize(colors=n, method=Image.MEDIANCUT)
            palette = quantised.getpalette() or []
            counts = sorted(quantised.getcolors() or [],
                            reverse=True)
    except Exception as e:  # noqa: BLE001
        return f"Couldn't read '{target.name}' as a picture: {e}"
    if not counts:
        return f"'{target.name}' opened but had no pixels to read."
    total = sum(c for c, _idx in counts)
    lines = [f"The dominant colours of {target.name}:"]
    for c, idx in counts[:n]:
        r, g, b = palette[idx * 3:idx * 3 + 3]
        share = 100.0 * c / total
        lines.append(f"• #{r:02X}{g:02X}{b:02X} — "
                     f"{_nearest_colour_name((r, g, b))} "
                     f"({share:.0f}% of the picture)")
    lines.append("(Names are the nearest everyday colour to the "
                 "exact hex — close, not official.)")
    return "\n".join(lines)


