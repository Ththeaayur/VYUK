_HEX_RE = re.compile(r"^#?([0-9A-Fa-f]{6})$")


def _parse_hex(value: str) -> tuple | None:
    """'#RRGGBB' or 'RRGGBB' → (r, g, b) ints, or None."""
    m = _HEX_RE.match((value or "").strip())
    if not m:
        return None
    digits = m.group(1)
    return tuple(int(digits[i:i + 2], 16) for i in (0, 2, 4))


def _hex_str(rgb: tuple) -> str:
    return "#{:02X}{:02X}{:02X}".format(*rgb)


def gradient_css(color_a: str, color_b: str, color_c: str = "",
                 angle: int = 135, save_preview: bool = True) -> str:
    """A CSS linear-gradient between two (or three) colours + a preview."""
    a = _parse_hex(color_a)
    if a is None:
        return (f"'{color_a}' isn't a colour I can read — give "
                "hex like #3B82F6.")
    b = _parse_hex(color_b)
    if b is None:
        return (f"'{color_b}' isn't a colour I can read — give "
                "hex like #3B82F6.")
    stops = [a, b]
    if (color_c or "").strip():
        c = _parse_hex(color_c)
        if c is None:
            return (f"'{color_c}' isn't a colour I can read — "
                    "give hex like #3B82F6, or leave the third "
                    "colour empty.")
        stops = [a, c, b]
    try:
        deg = int(angle)
    except (TypeError, ValueError):
        return f"'{angle}' isn't a whole number of degrees."
    deg %= 360
    if len(stops) == 2:
        css = (f"linear-gradient({deg}deg, {_hex_str(stops[0])}, "
               f"{_hex_str(stops[1])})")
    else:
        css = (f"linear-gradient({deg}deg, {_hex_str(stops[0])}, "
               f"{_hex_str(stops[1])} 50%, {_hex_str(stops[2])})")
    lines = [f"CSS gradient ({deg}°):", f"background: {css};"]
    if not save_preview:
        lines.append("No preview saved — ask with save_preview on "
                     "if you'd like a picture of it.")
        return "\n".join(lines)
    try:
        from PIL import Image
    except ImportError:
        lines.append("The CSS is ready, but Pillow isn't installed "
                     "here, so no preview picture could be drawn.")
        return "\n".join(lines)
    # Render small then upscale smooth (the creative pack's trick):
    # project each pixel onto the CSS angle axis — in CSS, 0deg
    # points up and angles run clockwise, so the direction is
    # (sin θ, −cos θ) — and interpolate along the stops.
    small, size = 128, 512
    theta = math.radians(deg)
    dx, dy = math.sin(theta), -math.cos(theta)
    projections = []
    for y in range(small):
        for x in range(small):
            projections.append((x - small / 2) * dx
                                 + (y - small / 2) * dy)
    lo, hi = min(projections), max(projections)
    span = (hi - lo) or 1.0
    img = Image.new("RGB", (small, small))
    px = img.load()
    pos = 0
    for y in range(small):
        for x in range(small):
            t = (projections[pos] - lo) / span
            pos += 1
            scaled = t * (len(stops) - 1)
            i = min(len(stops) - 2, int(scaled))
            frac = scaled - i
            p, q = stops[i], stops[i + 1]
            px[x, y] = tuple(round(p[ch] + (q[ch] - p[ch]) * frac)
                             for ch in range(3))
    dest = (Path.home() / "Pictures" / "Nova"
            / f"nova_gradient_{_hex_str(a)[1:]}_{_hex_str(b)[1:]}.png")
    try:
        dest.parent.mkdir(parents=True, exist_ok=True)
        final = _non_clobbering(dest)
        img.resize((size, size), Image.BICUBIC).save(final, "PNG")
    except OSError as e:
        lines.append(f"The CSS is ready, but the preview couldn't "
                     f"be saved: {e}")
        return "\n".join(lines)
    # R1a: verify the preview save by re-reading the file — the
    # preview is a world-act inside a mostly-text result, so the
    # return becomes an Outcome only when a preview was attempted.
    from . import tool_outcome as _outcome  # R1a: seam wiring

    ok, evidence = _outcome.file_written(final)
    if ok:
        lines.append(f"Preview saved to {final} (512×512)."
                     f"{_suffix_note(dest, final)}")
        return _outcome.verified("\n".join(lines), evidence)
    lines.append("The CSS is ready, but the preview picture could "
                 "not be confirmed on disk after saving it "
                 f"({evidence}) — the file may not be there.")
    return _outcome.unverified("\n".join(lines), evidence)


