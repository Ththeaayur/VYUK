# METRONOME — a click track, synthesised (writes one WAV)
# ---------------------------------------------------------------------------


def metronome(bpm: int = 90, beats: int = 16,
              accent_every: int = 4) -> str:
    """Render a click track: short sine blips, accented bars higher."""
    try:
        tempo = int(bpm)
    except (TypeError, ValueError):
        return f"'{bpm}' isn't a tempo in beats per minute."
    if not 30 <= tempo <= 240:
        return f"Metronome tempo runs 30–240 BPM — {tempo} is outside that."
    try:
        n_beats = int(beats)
    except (TypeError, ValueError):
        return f"'{beats}' isn't a whole number of beats."
    if not 1 <= n_beats <= 256:
        return f"A click track holds 1–256 beats — {n_beats} is outside that."
    try:
        accent = int(accent_every)
    except (TypeError, ValueError):
        return f"'{accent_every}' isn't a whole number of beats."
    if accent < 0:
        return "accent_every can't be negative — 0 means no accents."
    spb = 60.0 / tempo  # seconds per beat
    click_s = 0.05
    total = int(round(n_beats * spb * _SAMPLE_RATE))
    samples = array("h", bytes(2 * total))
    click_frames = int(click_s * _SAMPLE_RATE)
    for beat in range(n_beats):
        accented = accent > 0 and beat % accent == 0
        freq = 3000.0 if accented else 2000.0
        gain = 0.9 if accented else 0.6
        start = int(round(beat * spb * _SAMPLE_RATE))
        for i in range(click_frames):
            j = start + i
            if j >= total:
                break
            t = i / _SAMPLE_RATE
            env = math.exp(-60.0 * t)
            samples[j] = int(math.sin(2 * math.pi * freq * t)
                             * env * gain * 32767)
    dest = (Path.home() / "Music" / "Nova"
            / f"nova_metronome_{tempo}bpm.wav")
    try:
        dest.parent.mkdir(parents=True, exist_ok=True)
        final = _non_clobbering(dest)
        _save_wav(final, samples, channels=1)
    except OSError as e:
        return f"Couldn't save the click track to {dest}: {e}"
    seconds = n_beats * spb
    accent_note = (f"every {accent} beats accented (a higher click)"
                   if accent > 0 else "no accents")
    # R1b: re-read the saved WAV — _save_wav returning does not
    # prove it landed on disk.
    from . import tool_outcome as _outcome  # R1b: seam wiring

    ok, evidence = _outcome.file_written(final)
    if not ok:
        return (f"Couldn't confirm the saved click track: {evidence}.")
    return _outcome.verified(
        f"Metronome at {tempo} BPM — {n_beats} beats "
        f"({seconds:.1f} seconds), {accent_note}. Saved to "
        f"{final}.{_suffix_note(dest, final)} Synthesised "
        "click by click — nothing sampled.",
        evidence)


# ---------------------------------------------------------------------------
# BINAURAL TONE — one tone per ear, a beat in the difference (writes one WAV)
# ---------------------------------------------------------------------------


def binaural_tone(base_hz: int = 200, beat_hz: int = 10,
                  minutes: float = 2) -> str:
    """Stereo pair: base in the left ear, base+beat in the right."""
    try:
        import numpy as np
    except ImportError:
        return ("The audio part didn't make it into this build of "
                "VYUK, so I can't render stereo tones.")
    try:
        base = float(base_hz)
    except (TypeError, ValueError):
        return f"'{base_hz}' isn't a frequency in Hz."
    if not 40 <= base <= 1000:
        return f"Base tones run 40–1000 Hz — {base_hz} is outside that."
    try:
        beat = float(beat_hz)
    except (TypeError, ValueError):
        return f"'{beat_hz}' isn't a beat frequency in Hz."
    if not 0.5 <= beat <= 40:
        return (f"Beat frequencies run 0.5–40 Hz — {beat_hz} is "
                "outside that.")
    try:
        mins = float(minutes)
    except (TypeError, ValueError):
        return f"'{minutes}' isn't a number of minutes."
    if mins <= 0:
        return "Give a positive number of minutes."
    clipped = mins > 10
    mins = min(mins, 10.0)
    frames = int(round(mins * 60 * _SAMPLE_RATE))
    t = np.arange(frames, dtype=np.float64) / _SAMPLE_RATE
    left = np.sin(2 * np.pi * base * t)
    right = np.sin(2 * np.pi * (base + beat) * t)
    # Equal-power fade in/out (2 s each): sin/cos pair keeps the
    # perceived loudness steady across the ramp.
    fade = min(int(2 * _SAMPLE_RATE), frames // 2)
    if fade > 0:
        ramp = np.arange(fade, dtype=np.float64) / fade
        env = np.ones(frames)
        env[:fade] = np.sin(ramp * np.pi / 2)
        env[-fade:] = np.cos(ramp * np.pi / 2)
        left = left * env
        right = right * env
    stereo = np.empty(frames * 2, dtype=np.int16)
    stereo[0::2] = (left * 0.5 * 32767).astype(np.int16)
    stereo[1::2] = (right * 0.5 * 32767).astype(np.int16)
    samples = array("h", stereo.tobytes())
    dest = (Path.home() / "Music" / "Nova"
            / f"nova_binaural_{base:g}_{beat:g}.wav")
    try:
        dest.parent.mkdir(parents=True, exist_ok=True)
        final = _non_clobbering(dest)
        _save_wav(final, samples, channels=2)
    except OSError as e:
        return f"Couldn't save the binaural tone to {dest}: {e}"
    minutes_note = (f"{mins:g} minute(s)"
                    + (" (clamped from more — 10 minutes is the "
                       "cap, the files get big)" if clipped else ""))
    # R1b: re-read the saved WAV — _save_wav returning does not
    # prove it landed on disk.
    from . import tool_outcome as _outcome  # R1b: seam wiring

    ok, evidence = _outcome.file_written(final)
    if not ok:
        return (f"Couldn't confirm the saved binaural tone: {evidence}.")
    return _outcome.verified(
        f"Binaural tone saved to {final}: left ear {base:g} Hz, "
        f"right ear {base + beat:g} Hz, a {beat:g} Hz "
        f"difference, {minutes_note} long."
        f"{_suffix_note(dest, final)} Headphones are required — "
        "with speakers the two tones mix in the air and the "
        "beat effect is lost.",
        evidence)


